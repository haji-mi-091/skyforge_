# War Thunder wiki facts for the J-10C -> src/data/j10cWiki.js.
# Input: sources/wiki/j10c.html, saved from
# https://wiki.warthunder.com/unit/j_10c. The four-value rows on the page are
# RB reference / RB basic / AB reference / AB basic (same order as the J-16).
from pathlib import Path
import html,json,re
h=Path('sources/wiki/j10c.html').read_text(encoding='utf8')
text=[re.sub(r'\s+',' ',html.unescape(t)).strip() for t in re.split(r'<[^>]+>',re.sub(r'data-feature-popover="[^"]*"','',h))]
text=[t for t in text if t]
def after(label,n=1):
    i=text.index(label);return text[i+1:i+1+n]
num=lambda s:float(s.replace(',','').split()[0])
speed=[num(x) for x in after('12,000',6)[1:5]]
climb=[num(x) for x in after('Rate of Climb',4)];turn=[num(x) for x in after('Turn time',4)];base=[num(x)*1000 for x in after('Base weight',4)]
engine=re.search(r'WS-10B.*?Maximum\s*([\d,]+)\D*?kgf.*?Afterburner\s*([\d,]+)\D*?kgf',re.sub('<[^>]+>',' ',html.unescape(h)),re.S)
# Pylon table: one row per store, 11 slot columns (left wing tip -> right wing tip).
t=h[h.index('game-unit_slot-list'):];t=t[:t.index('</table>')];slots=[]
for row in re.findall(r'<tr>(.*?)</tr>',t,re.S)[1:]:
    cells=re.findall(r'<td[^>]*>(.*?)</td>',row,re.S)
    name=re.sub(r'\s+',' ',html.unescape(re.sub('<[^>]+>',' ',re.sub(r'data-feature-popover="[^"]*"','',cells[0])))).strip()
    slots.append({'name':name,'mass':num(cells[1]),'slots':[i+1 for i,c in enumerate(cells[2:]) if '<img' in c]})
a={'speedKmh':speed[0],'speedAltitude':12000,'climbMps':climb[0],'turnSeconds':turn[0],'ceiling':num(after('Max altitude')[0]),'takeoffRun':num(after('Takeoff Run')[0]),
   'crew':1,'length':num(after('Length')[0]),'span':num(after('Wingspan')[0]),'wingLoading':num(after('Wing Loading')[0]),'baseMass':base[0],
   'fuel':num(after('Fuel in main tanks')[0])*1000,'fuelMinutes':25,'dropTankFuel':num(after('Fuel in drop tanks')[0])*1000,
   'maxIas':num(after('Max Speed Limit (IAS)')[0]),'maxMach':num(after('Mach Number Limit')[0]),'gPositive':11,'gNegative':-4,'gearIas':num(after('Gear Speed Limit (IAS)')[0]),
   'engineCount':1,'engineDryKgf':num(engine[1]),'engineAbKgf':num(engine[2]),
   'payload':num(after('Max weight')[0]),'sidePayload':3500,'payloadImbalance':1750,'cannon':'23 mm Type 23-3','cannonAmmo':200,'cannonRpm':3396,'burstMassKg':9.85,
   'penetration':{'distance':[10,100,500,1000,1500,2000],'mm':[31,29,21,15,10,7]},
   'belts':{'default':['HEFI-T','AP-I','HEF-I'],'armored':['HEF-I','AP-I','AP-I','AP-I'],'air':['HEFI-T','HEF-I','HEFI-T','HEF-I','AP-I'],'stealth':['AP-I','HEF-I','HEF-I']}}
assert a['fuel']==2900 and a['engineDryKgf']==8620 and a['payload']==7000,a
source={'url':'https://wiki.warthunder.com/unit/j_10c','checked':'2026-10-21','mode':'RB reference','aircraft':a,
 'variants':{'rbBasic':{'speedKmh':speed[1],'climbMps':climb[1],'turnSeconds':turn[1],'baseMass':base[1]},'abReference':{'speedKmh':speed[2],'climbMps':climb[2],'turnSeconds':turn[2],'baseMass':base[2]},'abBasic':{'speedKmh':speed[3],'climbMps':climb[3],'turnSeconds':turn[3],'baseMass':base[3]}},
 'pylons':slots,
 'equipment':['dragChute','fuelDump','flaresChaff','MAW','radar KLJ-10A','IRST','RWR','ballisticComputer','HMD','nightVision','thermal','voiceWarnings'],
 'avionicsPolicy':'Runtime radar/RWR/alerts inherit F16CM Block52, as the J-16 does.'}
Path('src/data/j10cWiki.js').write_text('// Numerical public facts; generated by tools/import-j10c-wiki.py.\nexport const J10C_WIKI = '+json.dumps(source,ensure_ascii=False,indent=2)+';\n',encoding='utf8')
print(json.dumps(a,ensure_ascii=False))
