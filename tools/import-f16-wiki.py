# War Thunder wiki facts for the F-16CM Block 52 -> src/data/f16Wiki.js.
# Input: sources/wiki/f16.html, saved from
# https://wiki.warthunder.com/unit/f_16c_block_50 (War Thunder's closest unit;
# the game aircraft is a Block 52). The four-value rows on the page are
# RB reference / RB basic / AB reference / AB basic (same order as the J-16 / J-10C).
# Facts only: the F-16 flight coefficients are not driven by this file.
from pathlib import Path
import html,json,re
URL='https://wiki.warthunder.com/unit/f_16c_block_50'
h=Path('sources/wiki/f16.html').read_text(encoding='utf8')
text=[re.sub(r'\s+',' ',html.unescape(t)).strip() for t in re.split(r'<[^>]+>',re.sub(r'data-feature-popover="[^"]*"','',h))]
text=[t for t in text if t]
def after(label,n=1):
    i=text.index(label);return text[i+1:i+1+n]
num=lambda s:float(s.replace(',','').split()[0])
def field(fn):
    try:return fn()
    except (ValueError,IndexError):return None
plain=re.sub('<[^>]+>',' ',html.unescape(h))
engine=re.search(r'Maximum\s*([\d,]+)\D*?kgf.*?Afterburner\s*([\d,]+)\D*?kgf',plain,re.S)
# "Max speed at <altitude> m <RB ref> <RB basic> <AB ref> <AB basic> km/h"
speedRow=after('Max speed',5)
glimit=re.search(r'-(\d+)\s*/\s*(\d+)\s*G',plain)
# "Flap Speed Limit (IAS)  L / T  463 / 470 km/h" (landing / takeoff flaps)
flaps=field(lambda:[num(v) for v in after('Flap Speed Limit (IAS)',2)[1].replace('km/h','').split('/')])
a={'speedKmh':field(lambda:num(speedRow[3])),'speedAltitude':field(lambda:num(speedRow[1])),
   'gPositive':int(glimit.group(2)) if glimit else None,'gNegative':-int(glimit.group(1)) if glimit else None,
   'cannonAmmo':field(lambda:num(after('Ammunition')[0])),'climbMps':field(lambda:num(after('Rate of Climb',4)[0])),
   'turnSeconds':field(lambda:num(after('Turn time',4)[0])),'ceiling':field(lambda:num(after('Max altitude')[0])),'takeoffRun':field(lambda:num(after('Takeoff Run')[0])),
   'crew':1,'length':field(lambda:num(after('Length')[0])),'span':field(lambda:num(after('Wingspan')[0])),'wingLoading':field(lambda:num(after('Wing Loading')[0])),
   'baseMass':field(lambda:num(after('Base weight',4)[0])*1000),'fuel':field(lambda:num(after('Fuel in main tanks')[0])*1000),
   'dropTankFuel':field(lambda:num(after('Fuel in drop tanks')[0])*1000),'maxIas':field(lambda:num(after('Max Speed Limit (IAS)')[0])),
   'maxMach':field(lambda:num(after('Mach Number Limit')[0])),'gearIas':field(lambda:num(after('Gear Speed Limit (IAS)')[0])),
   'flapLandingIas':flaps[0] if flaps else None,'flapTakeoffIas':flaps[1] if flaps else None,
   'engineDryKgf':num(engine.group(1)) if engine else None,'engineAbKgf':num(engine.group(2)) if engine else None}
# M61A1 belt table: "<Belt> <A/B/C filling> <penetration mm at 10/100/500/1000/1500/2000 m>"
# rows between 'Available belts' and 'Suspended armament'.
BELT_IDS={'Default':'default','Air targets':'air','Stealth':'stealth','Armored targets':'armored','Ground targets':'ground','Universal':'universal'}
rows=text[text.index('Available belts'):text.index('Suspended armament')]
belts={};beltPenetration={}
for i,t in enumerate(rows):
    if t in BELT_IDS and i+7<len(rows):
        belts[BELT_IDS[t]]=rows[i+1].split('/');beltPenetration[BELT_IDS[t]]=[num(v) for v in rows[i+2:i+8]]
a['cannonBelts']=belts;a['beltPenetration']={'distance':[10,100,500,1000,1500,2000],'mm':beltPenetration}
missing=[k for k,v in a.items() if v is None]
source={'url':URL,'unit':'F-16C Block 50','note':'War Thunder wiki stat card (RB reference values); closest in-game unit to the F-16CM Block 52','missing':missing,'aircraft':a}
Path('src/data/f16Wiki.js').write_text('// Numerical public facts; generated by tools/import-f16-wiki.py.\nexport const F16_WIKI = '+json.dumps(source,ensure_ascii=False,indent=2)+';\n',encoding='utf8')
print(json.dumps(source,ensure_ascii=False))
